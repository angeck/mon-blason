#!/usr/bin/env python3
"""Pocket Club · tests des écrans dans un navigateur sans écran (Playwright), avec le faux client tests/faux_supabase.js.
Usage : python3 tests/ecrans.py [dossier_captures]   (lance un petit serveur local sur le dépôt)
Vérifie qu'aucune erreur JavaScript ne survient sur les écrans principaux et que les parcours clés fonctionnent."""
import http.server, os, sys, threading, functools
from playwright.sync_api import sync_playwright

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = sys.argv[1] if len(sys.argv) > 1 else None
FAKE = open(os.path.join(ROOT, 'tests', 'faux_supabase.js')).read()
http.server.SimpleHTTPRequestHandler.log_message = lambda *a: None
srv = http.server.ThreadingHTTPServer(('127.0.0.1', 8765), functools.partial(http.server.SimpleHTTPRequestHandler, directory=ROOT))
threading.Thread(target=srv.serve_forever, daemon=True).start()
results, errors = [], []

def check(name, cond):
    results.append((name, bool(cond)))

with sync_playwright() as p:
    b = p.chromium.launch()
    ctx = b.new_context(viewport={'width': 390, 'height': 844}, locale='fr-FR')
    ctx.route('https://cdn.jsdelivr.net/npm/@supabase/**', lambda r: r.fulfill(status=200, content_type='application/javascript', body=FAKE))
    ctx.route('https://fonts.googleapis.com/**', lambda r: r.fulfill(status=200, content_type='text/css', body=''))
    ctx.route('https://fonts.gstatic.com/**', lambda r: r.abort())
    pg = ctx.new_page()
    pg.on('pageerror', lambda e: errors.append(str(e)))
    pg.on('console', lambda m: errors.append(m.text) if m.type == 'error' else None)
    pg.add_init_script("navigator.serviceWorker && (navigator.serviceWorker.register = () => Promise.resolve())")
    pg.goto('http://127.0.0.1:8765/index.html')
    pg.wait_for_selector('.tb', timeout=8000)
    shot = lambda n: OUT and pg.screenshot(path=os.path.join(OUT, n + '.png'), full_page=True)
    txt = lambda: pg.inner_text('#app')
    has = lambda t: t.lower() in txt().lower()
    act = lambda sel: (pg.click(sel), pg.wait_for_timeout(250))

    check('accueil : salutation et rendez-vous à répondre', has('Salut Gaël') and has('À répondre'))
    check('accueil : demande à valider visible', has('1 demande à valider'))
    shot('01-accueil')
    act('[data-act=tab][data-i="1"]')
    check('agenda : réunion de bureau passée rangée dans « Passés »', has('Passés'))
    check('agenda : rendez-vous U9 et U11 affiché', has('Photo U9 et U11'))
    shot('02-agenda')
    act('[data-act=event][data-id=e1]')
    check('rendez-vous : coach encadrant ne répond pas pour lui', has('Tu encadres'))
    check('rendez-vous en série : deux choix de suppression', has('Supprimer cette séance') and has('Supprimer toutes les séances à venir'))
    act('[data-act=evdel][data-m=series]')
    check('suppression de série : confirmation avec le nombre de séances', has('Confirmer : 2 séances supprimées'))
    shot('03-rendez-vous')
    act('[data-act=evdel][data-m=series]')
    check('suppression de série : les 2 séances à venir ont disparu', pg.evaluate("window.__FAKE.events.filter(e => e.series_id === 's1').length") == 0)
    act('[data-act=tab][data-i="1"]')
    act('[data-act=event][data-id=e2]')
    act('[data-act=rsvp][data-p=p-lily][data-v=oui]')
    check('parent : réponse au nom de Lily enregistrée', pg.evaluate("window.__FAKE.event_responses.some(r => r.player_id === 'p-lily' && r.answer === 'oui')"))
    act('[data-act=back]')
    act('[data-act=evnew]')
    act('[data-act=evaud][data-v=team]')
    act('[data-act=evteam][data-id=t-u9]'); act('[data-act=evteam][data-id=t-u11]')
    check('formulaire : deux équipes choisies', has('Équipes (2)'))
    act('[data-act=evaud][data-v=people]')
    pg.check('[data-evpeople=u-s1]'); pg.wait_for_timeout(200)
    check('formulaire : personnes choisies', has('Personnes choisies (1)'))
    shot('04-nouveau-rendez-vous')
    pg.fill('#et', 'Commission buvette'); pg.click('#evf [type=submit]'); pg.wait_for_timeout(400)
    check('création pour des personnes choisies', pg.evaluate("window.__FAKE.events.some(e => e.title === 'Commission buvette' && e.audience === 'people' && e.people[0] === 'u-s1')"))
    act('[data-act=selmode]')
    pg.check('[data-evsel=e4]'); pg.wait_for_timeout(200)
    check('sélection multiple : barre de suppression', has('1 rendez-vous sélectionné'))
    act('[data-act=seldel]'); act('[data-act=seldel]')
    check('sélection multiple : rendez-vous supprimé', pg.evaluate("!window.__FAKE.events.some(e => e.id === 'e4')"))
    act('[data-act=tab][data-i="2"]'); act('[data-act=group][data-id=g1]')
    check('groupe : message et sondage', has('covoiturage') and has('Présent au plateau'))
    shot('05-groupe')
    act('[data-act=polldel]'); act('[data-act=polldel]')
    check('sondage à la corbeille, restaurable', has('supprimé par') and has('Restaurer'))
    act('[data-act=tab][data-i="3"]')
    check('équipe : rappel des dates de naissance', has('date de naissance manque'))
    shot('06-equipe')
    act('[data-act=player][data-id=p-tom]')
    check('fiche : contact importé du parent', has('Contact du parent (importé)'))
    shot('07-fiche')
    act('[data-act=pdel]'); act('[data-act=pdel]')
    check('fiche mise à la corbeille', pg.evaluate("!!window.__FAKE.players.find(p => p.id === 'p-tom').deleted_at"))
    act('[data-act=tab][data-i="4"]')
    check('club : code et demandes à valider', has('AB3CD4EF') and has('Zoé Martin'))
    pg.click('[data-trash] summary'); pg.wait_for_timeout(500)
    check('club : la corbeille montre la fiche', has('Tom Dupont'))
    shot('08-club')
    act('[data-act=restore]')
    check('restauration de la fiche', pg.evaluate("!window.__FAKE.players.find(p => p.id === 'p-tom').deleted_at"))
    act('[data-act=tab][data-i="3"]'); act('[data-act=import][data-id=t-u9]')
    pg.fill('#imt', 'DURAND;Léo;12/03/2018;Évry\nMARTIN;Zoé;02/05/2017;Ris'); act('[data-act=impcheck]')
    check('import sans en-tête : écran « Quelle colonne est quoi ? »', has('Quelle colonne est quoi'))
    shot('09-colonnes')
    act('[data-act=impmap]')
    check('import : 2 lignes à vérifier, nom et prénom séparés', has('2 lignes') and pg.input_value('#ir0first_name') == 'Léo' and pg.input_value('#ir0last_name') == 'DURAND')
    act('[data-act=impback]')
    pg.fill('#imt', 'Nom;Prénom;Mail\nDURAND;Léo;parent.leo@exemple.fr'); act('[data-act=impcheck]')
    check('import avec en-tête : pas d’écran des colonnes, e-mail repris', not has('Quelle colonne') and pg.input_value('#ir0email') == 'parent.leo@exemple.fr')
    check('import : case « Ne pas importer les coordonnées »', has('Ne pas importer les coordonnées'))
    pg.check('[data-impnocontact]'); pg.wait_for_timeout(200); act('[data-act=impok]')
    check('import sans les coordonnées', pg.evaluate("window.__CALLS.some(c => c[1] === 'import_players' && c[2].p_rows[0].email === null)"))
    act('[data-act=tab][data-i="0"]'); act('[data-act=account]')
    check('mon compte : données et suppression', has('Télécharger mes données') and has('Supprimer mon compte'))
    shot('10-compte')
    act('[data-act=legal]')
    check('mentions légales : adresse de contact', has('gael.monblason@gmail.com'))
    act('[data-act=back]')
    # ordinateur
    pg.set_viewport_size({'width': 1280, 'height': 900}); act('[data-act=back]'); act('[data-act=tab][data-i="0"]')
    shot('11-ordinateur')
    check('ordinateur : onglets en colonne', pg.evaluate("document.querySelector('.tb nav').getBoundingClientRect().width < 300"))
    # en-tête aux couleurs du club
    pg.evaluate("window.__FAKE.clubs[0].custom_header = true"); act('[data-act=refresh]')
    check('en-tête aux couleurs du club, texte lisible', pg.evaluate("getComputedStyle(document.querySelector('.hd')).backgroundColor") == 'rgb(194, 65, 12)')
    pg.set_viewport_size({'width': 390, 'height': 844}); shot('12-entete-club')
    # écran de connexion
    pg2 = ctx.new_page(); pg2.on('pageerror', lambda e: errors.append(str(e)))
    pg2.add_init_script("window.__LOGGED_OUT = true")
    pg2.goto('http://127.0.0.1:8765/index.html'); pg2.wait_for_selector('#authf', timeout=8000)
    check('connexion : formulaire', 'Me connecter' in pg2.inner_text('#app'))
    OUT and pg2.screenshot(path=os.path.join(OUT, '00-connexion.png'), full_page=True)
    b.close()
srv.shutdown()
errs = [e for e in errors if 'favicon' not in e and 'Failed to load resource' not in e]
for n, ok in results:
    print(('  ok    · ' if ok else '  ÉCHEC · ') + n)
print(f"\n   {sum(ok for _, ok in results)} réussis sur {len(results)} tests d'écrans")
print('   Erreurs JavaScript : ' + (' | '.join(errs) if errs else 'aucune'))
sys.exit(0 if all(ok for _, ok in results) and not errs else 1)
